import assert from 'node:assert/strict';
import {mkdtemp} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
process.env.DATA_DIR=await mkdtemp(join(tmpdir(),'school-chat-identity-'));
const {postChat,setConfig,chatHistory,hub}=await import('../server/events.js');
const {identityLabel}=await import('../src/characterIdentity.js');
const messages=[];hub.broadcast=m=>messages.push(m);
await setConfig({chat:'always',event:'none',schedule:'always'});
const student={uid:'student-1',identity:{name:'Nguyen Van An',role:'student',cls:'12A3',year:'2015-2018'}};
assert.equal(await postChat(student,{name:'Fake name',text:'hello'}),null);
const chat=messages.find(m=>m.type==='chat').message;
assert.equal(chat.name,identityLabel(student.identity));assert(chat.name.includes('12A3')&&chat.name.includes('2015-2018'));
assert.equal(chat.authorId,'student-1');assert(!chat.name.includes('Fake name'));
const teacher={uid:'teacher-1',identity:{role:'teacher',name:'Teacher',subject:'Math',year:'2023-2026',cls:'12A3'}};
await postChat(teacher,{text:'welcome'});
const teacherChat=messages.filter(m=>m.type==='chat').at(-1).message;
assert(teacherChat.name.includes('Math'));assert(!teacherChat.name.includes('2023-2026')&&!teacherChat.name.includes('12A3'));
assert.equal(typeof await postChat({uid:'unregistered'},{name:'guest',text:'hello'}),'string');
const history=await chatHistory();assert.equal(history.length,2);assert.deepEqual(history[0].identity,chat.identity);
console.log('PASS chat uses character identity, ignores independent names, teacher subject only, stable author ID, history retains identity, missing profile rejected');
